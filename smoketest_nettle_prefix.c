#include <nettle/aes.h>
#include <nettle/sha2.h>
#include <stdio.h>
#include <string.h>

int main(void) {
    /* FIPS-197 Appendix B AES-128 known-answer test */
    static const uint8_t key[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f
    };
    static const uint8_t plaintext[16] = {
        0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,
        0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff
    };
    static const uint8_t expected[16] = {
        0x69,0xc4,0xe0,0xd8,0x6a,0x7b,0x04,0x30,
        0xd8,0xcd,0xb7,0x80,0x70,0xb4,0xc5,0x5a
    };
    struct aes128_ctx ctx;
    uint8_t out[16];
    aes128_set_encrypt_key(&ctx, key);
    aes128_encrypt(&ctx, 16, out, plaintext);
    if (memcmp(out, expected, 16) != 0) {
        printf("AES-128 FAIL\n");
        return 1;
    }
    printf("AES-128 (nettle/aes.h): OK\n");

    struct sha256_ctx sctx;
    uint8_t digest[32];
    sha256_init(&sctx);
    sha256_update(&sctx, 3, (const uint8_t *)"abc");
    sha256_digest(&sctx, digest);
    static const uint8_t expected_sha256[32] = {
        0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,
        0x41,0x41,0x40,0xde,0x5d,0xae,0x22,0x23,
        0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,
        0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad
    };
    if (memcmp(digest, expected_sha256, 32) != 0) {
        printf("SHA-256 FAIL\n");
        return 1;
    }
    printf("SHA-256 (nettle/sha2.h): OK\n");
    return 0;
}
